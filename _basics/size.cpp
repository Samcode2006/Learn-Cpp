#include <iostream>
#include <string>
using namespace std;

int main()
{
    cout << "\nSize of int: " << sizeof(int) << " Bytes";
    cout << "\nSize of float: " << sizeof(float) << " Bytes";
    cout << "\nSize of double: " << sizeof(double) << " Bytes";
    cout << "\nSize of string: " << sizeof(string) << " Bytes";
    cout << "\nSize of char: " << sizeof(char) << " Bytes\n";

    return 0;
}
